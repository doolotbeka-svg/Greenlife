export type Language = 'ky' | 'ru';
export type Currency = 'KGS' | 'RUB' | 'USD';

export const CURRENCY_SYMBOLS: Record<Currency, string> = {
  KGS: 'сом',
  RUB: '₽',
  USD: '$',
};

// Rates relative to KGS
export const CURRENCY_RATES_FROM_KGS: Record<Currency, number> = {
  KGS: 1,
  RUB: 1.02,
  USD: 0.0112,
};

export function formatPrice(amountInKgs: number, currency: Currency): string {
  if (currency === 'KGS') {
    return `${Math.round(amountInKgs).toLocaleString('ru-RU')} сом`;
  }
  if (currency === 'RUB') {
    return `${Math.round(amountInKgs * CURRENCY_RATES_FROM_KGS.RUB).toLocaleString('ru-RU')} ₽`;
  }
  if (currency === 'USD') {
    const usd = (amountInKgs * CURRENCY_RATES_FROM_KGS.USD).toFixed(1);
    return `$${usd}`;
  }
  return `${amountInKgs} сом`;
}

